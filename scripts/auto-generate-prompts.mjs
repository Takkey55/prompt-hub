// Helper to pad numbers
function pad(num) {
  return num < 10 ? `0${num}` : `${num}`;
}

async function generateWeeklyPrompts() {
  console.log('🚀 Checking existing prompts...');
  if (!fs.existsSync(PROMPTS_DIR)) {
    fs.mkdirSync(PROMPTS_DIR, { recursive: true });
  }

  const existingFiles = new Set(fs.readdirSync(PROMPTS_DIR).map((f) => f.replace(/\.md$/, '')));
  console.log(`Found ${existingFiles.size} existing prompt articles.`);

  const now = new Date();
  const dateStr = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;

  let generatedCount = 0;
  const targetPerCategory = 2; // 2 items per category = 10 items total
  const categoryCount = {};
  CATEGORIES.forEach((c) => (categoryCount[c] = 0));

  // Iterate over database
  for (const item of PROMPT_DATABASE) {
    if (generatedCount >= 10) break;
    if (categoryCount[item.category] >= targetPerCategory) continue;

    let slug = item.slugPattern;
    // If slug already exists, generate a numbered unique slug
    let counter = 1;
    while (existingFiles.has(slug)) {
      counter++;
      slug = `${item.slugPattern}-v${counter}`;
    }

    const filePath = path.join(PROMPTS_DIR, `${slug}.md`);

    const markdownContent = `---
title: "${item.title.replace(/"/g, '\\"')}"
description: "${item.description.replace(/"/g, '\\"')}"
category: "${item.category}"
targetModel: "${item.targetModel}"
timeSaved: "${item.timeSaved}"
pubDate: ${dateStr}
noteUrl: "${item.noteUrl || 'https://note.com/prompt_hub_official'}"
promptText: |
${item.promptText.split('\n').map((line) => '  ' + line).join('\n')}
---

${item.bodyGuide}
`;

    fs.writeFileSync(filePath, markdownContent, 'utf-8');
    existingFiles.add(slug);
    categoryCount[item.category]++;
    generatedCount++;
    console.log(`✅ [${generatedCount}/10] Generated: ${slug}.md (${item.category})`);
  }

  console.log(`🎉 Successfully generated ${generatedCount} new prompt articles.`);
}

generateWeeklyPrompts().catch((err) => {
  console.error('❌ Error generating weekly prompts:', err);
  process.exit(1);
});
